#!/usr/bin/env node
// Generate TypeScript types for `components.schemas` of an OpenAPI JSON (no dependency).
//   node scripts/gen-api-types.mjs [openapi.json] [out.ts]
// Defaults: src/openapi.snapshot.json -> src/api.gen.ts. `make api-types` refreshes the snapshot first.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const input = process.argv[2] ?? resolve(root, "src/openapi.snapshot.json");
const output = process.argv[3] ?? resolve(root, "src/api.gen.ts");
const spec = JSON.parse(readFileSync(input, "utf8"));
const schemas = spec.components?.schemas ?? {};

const ident = (name) => {
  const id = name.replace(/[^A-Za-z0-9_]/g, "_").replace(/_+$/g, "");
  return /^[0-9]/.test(id) ? `_${id}` : id;
};
const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
const lit = (v) => (v === null ? "null" : JSON.stringify(v));

function ts(s, indent) {
  if (s === true || s === undefined) return "unknown";
  if (s === false) return "never";
  if (s.$ref) return ident(s.$ref.split("/").pop());
  if (s.enum) return s.enum.map(lit).join(" | ") || "never";
  if ("const" in s) return lit(s.const);
  const union = s.anyOf ?? s.oneOf;
  if (union) return union.map((u) => ts(u, indent)).join(" | ") || "never";
  if (s.allOf) return s.allOf.map((u) => ts(u, indent)).join(" & ") || "unknown";
  const types = Array.isArray(s.type) ? s.type : s.type ? [s.type] : [];
  if (types.length > 1) return types.map((t) => ts({ ...s, type: t }, indent)).join(" | ");
  switch (types[0]) {
    case "string": return "string";
    case "integer": case "number": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": {
      if (s.prefixItems) return `[${s.prefixItems.map((i) => ts(i, indent)).join(", ")}]`;
      const item = ts(s.items, indent);
      return /[|&]/.test(item) ? `(${item})[]` : `${item}[]`;
    }
    case "object": return object(s, indent);
    default: return s.properties ? object(s, indent) : "unknown";
  }
}

function object(s, indent) {
  const pad = "  ".repeat(indent + 1);
  const req = new Set(s.required ?? []);
  const lines = Object.entries(s.properties ?? {}).map(
    ([k, v]) => `${pad}${key(k)}${req.has(k) ? "" : "?"}: ${ts(v, indent + 1)};`);
  if (s.additionalProperties) {
    const ap = s.additionalProperties === true ? "unknown" : ts(s.additionalProperties, indent + 1);
    lines.push(`${pad}[key: string]: ${ap};`);
  }
  return lines.length ? `{\n${lines.join("\n")}\n${"  ".repeat(indent)}}` : "Record<string, never>";
}

const out = [
  "// GENERATED by scripts/gen-api-types.mjs from src/openapi.snapshot.json. Do not edit; run `make api-types`.",
  "",
];
for (const name of Object.keys(schemas).sort()) {
  const s = schemas[name];
  const body = ts(s, 0);
  out.push(body.startsWith("{") && !s.enum ? `export interface ${ident(name)} ${body}` : `export type ${ident(name)} = ${body};`);
  out.push("");
}
writeFileSync(output, out.join("\n"));
console.log(`${Object.keys(schemas).length} schemas -> ${output}`);
